#!/usr/bin/env node
// Builds the Discord posts for one challenge week straight from the registry and the agent logs,
// so the post always matches what is live. Fails if any post is over Discord's 2,000-character limit.
//
//   node scripts/submissions.mjs 5        -> writes submissions/week-05.md
//   node scripts/submissions.mjs all      -> every week that has components

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const SITE = "https://lofi-component-lab.vercel.app";
const REPO = "https://github.com/EsamAhmed1/lofi-component-lab";
// Discord allows 2,000 characters, but the @LofiDB mention and emoji count for more than they show,
// so posts are kept well under it.
const LIMIT = 1500;

/** Reads a string field written as "...", '...' or `...` (template literals without ${}). */
function field(block, name) {
  const re = new RegExp(`\\b${name}:\\s*(?:"((?:\\\\.|[^"\\\\])*)"|'((?:\\\\.|[^'\\\\])*)'|\`((?:\\\\.|[^\`\\\\])*)\`)`);
  const m = block.match(re);
  if (!m) return undefined;
  const raw = m[1] ?? m[2] ?? m[3];
  return raw.replace(/\\(["'`\\])/g, "$1").replace(/\\n/g, "\n");
}

function number(block, name) {
  const m = block.match(new RegExp(`\\b${name}:\\s*(\\d+)`));
  return m ? Number(m[1]) : undefined;
}

/** Splits an exported array literal into its top-level `{ ... }` objects. */
function objects(source) {
  const start = source.indexOf("= [");
  const out = [];
  let depth = 0, from = -1, quote = null;
  for (let i = start; i < source.length; i++) {
    const c = source[i];
    if (quote) {
      if (c === "\\") i++;
      else if (c === quote) quote = null;
      continue;
    }
    if (c === '"' || c === "'" || c === "`") quote = c;
    else if (c === "{") { if (depth++ === 0) from = i; }
    else if (c === "}") { if (--depth === 0) out.push(source.slice(from, i + 1)); }
    else if (c === "]" && depth === 0) break;
  }
  return out;
}

function components() {
  const dir = path.join(ROOT, "src", "registry", "weeks");
  return readdirSync(dir)
    .filter((f) => /^week-\d+\.ts$/.test(f))
    .flatMap((f) => objects(readFileSync(path.join(dir, f), "utf8")))
    .map((b) => ({
      slug: field(b, "slug"),
      name: field(b, "name"),
      kind: field(b, "kind"),
      week: number(b, "week"),
      source: field(b, "source"),
      prompt: field(b, "postPrompt") ?? field(b, "prompt"),
    }));
}

function logs() {
  return objects(readFileSync(path.join(ROOT, "src", "registry", "logs.ts"), "utf8")).map((b) => ({
    week: number(b, "week"),
    task: field(b, "task"),
    agent: field(b, "agent"),
    post: field(b, "post") ?? field(b, "workflow"),
    result: field(b, "result"),
  }));
}

const pad = (n) => String(n).padStart(2, "0");
const header = `LofiStack 90 Day Build Challenge:\nGALLERY: ${SITE}/\n\n`;

function componentPost(c, i) {
  return (
    header +
    `post ${i + 1} (${c.name}):\nWeek: ${pad(c.week)}\nType: ${c.kind}\nComponent name: ${c.name}\n` +
    `Live link: ${SITE}/components/${c.slug}\nRepo link: ${REPO}/blob/main/${c.source}\n` +
    `Prompt:\n${c.prompt.trim()} @LofiDB`
  );
}

function logPost(l, i) {
  return (
    header +
    `post ${i + 1} (Agent log):\nWeek: ${pad(l.week)}\nTask: ${l.task}\nAgent: ${l.agent}\n` +
    `Prompt or workflow:\n${l.post.trim()}\nResult: ${l.result.trim()}\n` +
    `Logs: ${SITE}/logs @LofiDB`
  );
}

function build(week) {
  const posts = [
    ...components().filter((c) => c.week === week).map((c) => ({ kind: "Component", text: c })),
    ...logs().filter((l) => l.week === week).map((l) => ({ kind: "Agent log", text: l })),
  ].map((p, i) => ({ kind: p.kind, body: p.kind === "Component" ? componentPost(p.text, i) : logPost(p.text, i) }));
  if (!posts.length) return null;

  let md = `# Week ${pad(week)} submissions\n\nPost each block in the lofidb channel as its own message. Generated by \`node scripts/submissions.mjs ${week}\`.\n`;
  let failed = false;
  posts.forEach((p, i) => {
    const len = p.body.length;
    if (len > LIMIT) failed = true;
    md += `\n## Post ${i + 1}: ${p.kind} (${len} characters${len > LIMIT ? `, OVER THE ${LIMIT} TARGET` : ""})\n\n\`\`\`\n${p.body}\n\`\`\`\n`;
  });
  writeFileSync(path.join(ROOT, "submissions", `week-${pad(week)}.md`), md);
  console.log(`week ${pad(week)}: ${posts.map((p) => p.body.length).join(", ")} chars${failed ? "  <-- too long" : ""}`);
  return !failed;
}

const arg = process.argv[2];
const weeks = arg === "all" ? [...new Set(components().map((c) => c.week))].sort((a, b) => a - b) : [Number(arg)];
if (!weeks.length || weeks.some((w) => !Number.isInteger(w))) {
  console.error("usage: node scripts/submissions.mjs <week|all>");
  process.exit(1);
}
const ok = weeks.map(build).every((r) => r !== false);
if (!existsSync(path.join(ROOT, "submissions"))) process.exit(1);
process.exit(ok ? 0 : 1);
